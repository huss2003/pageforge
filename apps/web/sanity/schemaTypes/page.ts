import { DocumentIcon } from '@sanity/icons/Document'
import { HomeIcon } from '@sanity/icons/Home'
import { RocketIcon } from '@sanity/icons/Rocket'
import { SparklesIcon } from '@sanity/icons/Sparkles'
import { registry, type BlockKind } from '@pageforge/blocks'
import { defineArrayMember, defineField, defineType } from 'sanity'
import { blockTypes } from './blocks'
import { textField } from './fields'

export const pageKindOptions = [
  { title: 'Home', value: 'home' },
  { title: 'Platform', value: 'platform' },
  { title: 'Industry', value: 'industry' },
  { title: 'Case study', value: 'caseStudy' },
  { title: 'Campaign landing page', value: 'landing' },
  { title: 'Other page', value: 'page' },
]

const kindTitle = (kind: unknown) => pageKindOptions.find((o) => o.value === kind)?.title ?? 'Page'

/**
 * A marketing page: SEO fields plus an ordered list of blocks. Mirrors
 * `pageSchema` in @pageforge/blocks. The same document shape is written by
 * editors in Studio, by the seed script and by the Factory's writer agent.
 */
export const page = defineType({
  name: 'page',
  title: 'Page',
  type: 'document',
  icon: DocumentIcon,
  groups: [
    { name: 'content', title: 'Content', default: true },
    { name: 'seo', title: 'SEO' },
    { name: 'settings', title: 'Settings' },
  ],
  fields: [
    textField({ name: 'title', title: 'Title', max: 90, group: 'content' }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'settings',
      description:
        'Lowercase words joined by hyphens. Sets the URL: industries live under /industries, case studies under /case-studies, campaign pages under /lp.',
      options: { source: 'title', maxLength: 80 },
      validation: (rule) =>
        rule.required().custom((value) => {
          const slug = value?.current
          if (!slug) return 'Required'
          if (slug.length > 80) return 'Keep the slug under 80 characters.'
          return /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || 'Use lowercase words joined by hyphens.'
        }),
    }),
    defineField({
      name: 'kind',
      title: 'Page type',
      type: 'string',
      group: 'settings',
      options: { list: pageKindOptions, layout: 'radio' },
      initialValue: 'page',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'seo',
      title: 'Search and sharing',
      type: 'object',
      group: 'seo',
      fields: [
        textField({
          name: 'title',
          title: 'SEO title',
          max: 60,
          description: '"| Hoverline" is added automatically.',
        }),
        textField({
          name: 'description',
          title: 'Meta description',
          max: 160,
          description: 'Shown under the title in search results and link previews.',
        }),
        defineField({
          name: 'noindex',
          title: 'Hide from search engines',
          type: 'boolean',
          description:
            'For campaign pages made for one prospect. Hidden pages are left out of the sitemap.',
          initialValue: false,
        }),
      ],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'blocks',
      title: 'Blocks',
      type: 'array',
      group: 'content',
      description:
        'Sections in page order. The first block must be a Hero; a Call to action or Demo request form goes last.',
      of: blockTypes.map((t) => defineArrayMember({ type: t.name })),
      options: {
        insertMenu: {
          views: [{ name: 'list' }],
        },
      },
      validation: (rule) =>
        rule
          .required()
          .min(1)
          .max(14)
          .custom((blocks) => {
            const list = (blocks ?? []) as { _type: BlockKind }[]
            if (!list.length) return true
            if (list[0]?._type !== 'hero') return 'The first block must be a Hero.'
            for (const [i, b] of list.entries()) {
              const def = registry[b._type]
              if (!def) continue
              if (def.placement === 'first' && i !== 0)
                return `${def.title} must be the first block.`
              if (def.placement === 'last' && i !== list.length - 1) {
                return `${def.title} must be the last block.`
              }
              const count = list.filter((x) => x._type === b._type).length
              if (count > def.maxPerPage) {
                return `Use ${def.title} at most ${def.maxPerPage} time${def.maxPerPage === 1 ? '' : 's'} per page.`
              }
            }
            return true
          }),
    }),
    defineField({
      name: 'generatedBy',
      title: 'Generated by',
      type: 'object',
      group: 'settings',
      readOnly: true,
      description: 'Set when the PageForge Factory wrote this page.',
      options: { collapsible: true, collapsed: true },
      fields: [
        defineField({ name: 'runId', title: 'Run id', type: 'string' }),
        defineField({ name: 'model', title: 'Model', type: 'string' }),
      ],
    }),
  ],
  orderings: [
    { title: 'Title', name: 'titleAsc', by: [{ field: 'title', direction: 'asc' }] },
    {
      title: 'Recently edited',
      name: 'updatedDesc',
      by: [{ field: '_updatedAt', direction: 'desc' }],
    },
  ],
  preview: {
    select: {
      title: 'title',
      slug: 'slug.current',
      kind: 'kind',
      noindex: 'seo.noindex',
      run: 'generatedBy.runId',
    },
    prepare: ({ title, slug, kind, noindex, run }) => ({
      title,
      subtitle: [kindTitle(kind), slug ? `/${slug}` : null, noindex ? 'hidden from search' : null]
        .filter(Boolean)
        .join(' · '),
      media: run
        ? SparklesIcon
        : kind === 'home'
          ? HomeIcon
          : kind === 'landing'
            ? RocketIcon
            : DocumentIcon,
    }),
  },
})
