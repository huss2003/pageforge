import type { Metadata } from 'next'
import Link from 'next/link'
import { notFound } from 'next/navigation'
import { BlockRenderer } from '@pageforge/ui/blocks'
import { formatClock } from '@/lib/factory/format'
import { getStore } from '@/lib/factory/store'

export const dynamic = 'force-dynamic'

type Props = { params: Promise<{ slug: string }> }

async function load(slug: string) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) return null
  return getStore().findPublished('demo', slug)
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const run = await load((await params).slug)
  return {
    title: { absolute: run?.page?.seo.title ?? 'Page not found' },
    description: run?.page?.seo.description,
    robots: { index: false, follow: false },
  }
}

/** A page published from a public demo run. Sandbox only: never indexed, never in Sanity. */
export default async function SandboxPage({ params }: Props) {
  const run = await load((await params).slug)
  if (!run?.page) notFound()

  return (
    <>
      <div className="border-b border-line bg-surface-raised text-sm">
        <div className="mx-auto flex max-w-6xl flex-wrap items-center gap-x-4 gap-y-1 px-4 py-2 sm:px-6">
          <span>
            Generated by PageForge
            {run.timeToShipMs != null && (
              <>
                {' '}
                in{' '}
                <span className="font-semibold tabular-nums">
                  {formatClock(run.timeToShipMs)}
                </span>{' '}
                from brief to live
              </>
            )}
          </span>
          <span className="text-fg-muted">Demo page for a fictional company. Not indexed.</span>
          <Link href={`/factory/runs/${run.id}`} className="ml-auto underline underline-offset-4">
            See how it was built
          </Link>
        </div>
      </div>
      <main>
        <BlockRenderer blocks={run.page.blocks} />
      </main>
    </>
  )
}
